async function fillIfEmpty(
  collection: string,
  docs: Record<string, unknown>[],
) {
  const c = mongoose.connection.collection(collection);
  if (await c.estimatedDocumentCount()) {
    console.log(`${collection}: not empty, skipped`);
    return;
  }
  const now = new Date();
  await c.insertMany(
    docs.map((d) => ({ ...d, createdAt: now, updatedAt: now })),
  );
  console.log(`${collection}: ${docs.length} inserted`);
}

async function main() {
  // Bun loads backend/.env into process.env.
  await mongoose.connect(process.env.MONGO_URL!);
  const day = 86_400_000;
  await fillIfEmpty(
    'articleentities',
    articles.map((a, i) => {
      const body = a.body.trim();
      return {
        ...a,
        body,
        status: 'published',
        publishedAt: new Date(Date.now() - (articles.length - i) * day),
        readingMinutes: readingMinutes(body),
      };
    }),
  );
  await fillIfEmpty(
    'newsentities',
    news.map((n) => ({
      ...n,
      startsAt: new Date(n.startsAt),
      endsAt: n.endsAt ? new Date(n.endsAt) : null,
    })),
  );
  await fillIfEmpty(
    'faqentities',
    faqs.map((f, i) => ({ ...f, order: i })),
  );
  await mongoose.disconnect();
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
